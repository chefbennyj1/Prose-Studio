exports.CHAPTER_ONE = `The salt road ran out three miles short of the sea, and nobody in Hale could tell her why.

Mara walked it anyway. The stone went from cut blocks to rubble to a suggestion in the grass, and then to nothing at all, and she stood at the nothing for a long time with the wind coming off the water and her boots full of yesterday's rain. Behind her the road was four hundred years old. In front of her it was a field.

She had asked at the inn and been given three answers, which is the same as being given none. The road ran out because the money ran out. The road ran out because the men who built it walked into the sea one winter and did not come back. The road ran out because it had never been meant to reach the water in the first place, and only a stranger would assume it had.

That last one had come from the woman behind the bar, who said it quietly and did not look up from the glass she was drying.

"You think I'm wrong," Mara said.

"I think you came a long way to look at a field."

It was not an answer either, but it was the first thing anyone had said to her in Hale that sounded like it cost something.

She went back the next morning with the survey maps and walked the last mile slowly, counting her steps, stopping where the stone gave out. The grass there grew differently. Not better or worse — differently, in a line, the way grass does when something underneath it has not rotted evenly. She knelt and pushed her fingers into the soil and felt the edge of something flat and worked and deliberately buried.

The road did not run out. The road had been covered.

That was a different question, and a worse one, and she sat back on her heels in the wet field and let herself understand that she would not be leaving Hale on Thursday.

By the time she walked back the light had gone amber and the town looked briefly like a place she might have chosen. Smoke from the chimneys. A dog barking at nothing with tremendous conviction. The inn's windows the colour of weak tea.

The woman behind the bar watched her come in with mud to the knee and said nothing, which Mara had begun to recognise as a kind of speech.

"Four hundred years," Mara said, sitting down. "Who covers a road?"

"Someone who wants it not to be walked."

"Or someone who wants it not to be found."

"That's the same thing, mostly." The woman set a glass down without being asked. "Round here it's the same thing entirely."

Mara turned the glass without drinking from it. Outside, the light finished going, and the field at the end of the road lay under the dark with whatever was left of the stone still holding its line beneath the grass, patient as it had been since before anyone in the room was born.

She thought about the three answers again. The money. The men. The claim that it had never been meant to reach the sea.

Someone had gone to a great deal of trouble to make the third one true.

"I'll need a spade," she said.

The woman almost smiled. "You'll need more than a spade."`;

exports.CHAPTER_TWO = `The spade came from a man called Ordish, who charged her twice what it was worth and threw in the advice for nothing.

"You'll hit water before you hit stone," he said. "Everyone does. That field drains into the estuary and the estuary comes back up through it twice a day whether you like it or not."

"Then I'll dig between tides."

"You'll dig between tides for a fortnight and then you'll stop." He said it without any unkindness at all, which made it worse. "People have dug there before, miss. It's not a new idea you've had."

That stopped her more effectively than an argument would have.

"Who?"

Ordish thought about it. He was the kind of man who genuinely thought about a question before answering it, and there were not many of those left anywhere.

"My father, once. A surveyor from the county, about twenty years back. And a girl before that, before I was born, who I only know about because my mother used to bring her up whenever I got an idea above myself."

"What happened to them?"

"Nothing happened to them." He handed her the spade. "That's the part nobody likes. Nothing happened to any of them. They dug, and they found nothing, and they went home, and that was the whole of it. It's not a curse. It's worse than a curse. It's just a field."

Mara took the spade.

"Then I'll be the fourth person to find nothing," she said, "and Hale can tell the story about me instead."

She dug for six days.

On the first day she found grass, and under the grass a foot of black soil that smelled like the inside of a church. On the second she found the water Ordish had promised, coming up brown and unhurried and filling the trench behind her as fast as she emptied it. On the third she moved twenty yards inland and started again, and on the fourth she found a horseshoe, which she kept, and a great deal of broken pottery, which she did not.

On the fifth day the trench went down three feet and stopped, and she cleared it with her hands, and it was stone — cut, laid, fitted, and running exactly where the road would have run if the road had gone on.

On the sixth day she followed it eleven yards toward the water and found the place where someone had broken it apart deliberately, block by block, and stacked the pieces to one side as neatly as plates.`;
